#!/usr/bin/env python3
"""Generate flrw_nu_table.h: Fermi-Dirac energy density and pressure of one neutrino species.

    F(y) = C int_0^inf q^2 sqrt(q^2 + y^2) / (e^q + 1) dq
    P(y) = C int_0^inf q^4 / (3 sqrt(q^2 + y^2)) / (e^q + 1) dq,     C = 120 / (7 pi^4)

so that F(0) = 1 and P(0) = 1/3 (rho and p in units of the massless value), y = m / (k_B T_nu).

The table holds ln F, ln P and their first and second derivatives with respect to t = ln y on a
uniform grid in t, for quintic Hermite interpolation (relative error ~1e-12). Outside the table,
flrw_kit.c uses the small-y series and the large-y expansion.

The integrals are split at q = 2: on [0, 2] the substitution q = y sinh(s) removes the branch points
of sqrt(q^2 + y^2) at q = +-iy (Gauss-Legendre in s), and [2, inf) uses Gauss-Laguerre.
Relative accuracy of the moments is ~1e-14.

Usage: python3 tools/gen_nu_table.py > flrw_nu_table.h      (requires numpy)
"""
import numpy as np
from numpy.polynomial.laguerre import laggauss
from numpy.polynomial.legendre import leggauss

C = 120.0 / (7.0 * np.pi**4)
Q0 = 2.0
XS, WS = leggauss(32)
XL, WL = laggauss(48)

T0 = np.log(1e-3)  # first grid point, t = ln y
H = 0.05           # grid spacing in t
N = 324            # last grid point T0 + (N-1) H > ln(1e4)


def moments(y):
    """F, dF/dy, d2F/dy2, P, dP/dy, d2P/dy2"""
    smax = np.arcsinh(Q0 / y)
    s = 0.5 * smax * (XS + 1.0)
    q1 = y * np.sinh(s)
    e1 = y * np.cosh(s)
    w1 = 0.5 * smax * WS * e1 / (np.exp(q1) + 1.0)  # dq = y cosh(s) ds
    q2 = Q0 + XL
    e2 = np.sqrt(q2 * q2 + y * y)
    w2 = WL * np.exp(XL) / (np.exp(q2) + 1.0)
    q = np.concatenate([q1, q2])
    e = np.concatenate([e1, e2])
    w = np.concatenate([w1, w2])
    F = np.sum(w * q**2 * e)
    Fy = np.sum(w * q**2 * y / e)
    Fyy = np.sum(w * q**4 / e**3)
    P = np.sum(w * q**4 / (3.0 * e))
    Py = -np.sum(w * q**4 * y / (3.0 * e**3))
    Pyy = -np.sum(w * q**4 * (q * q - 2.0 * y * y) / (3.0 * e**5))
    return C * np.array([F, Fy, Fyy, P, Py, Pyy])


def row(t):
    y = np.exp(t)
    F, Fy, Fyy, P, Py, Pyy = moments(y)
    out = []
    for G, Gy, Gyy in ((F, Fy, Fyy), (P, Py, Pyy)):
        Gt = y * Gy
        Gtt = y * Gy + y * y * Gyy
        Lt = Gt / G
        out += [np.log(G), Lt, Gtt / G - Lt * Lt]
    return out


def main():
    print("/* Generated by tools/gen_nu_table.py -- do not edit.")
    print(" * Rows: ln F, d lnF/dt, d2 lnF/dt2, ln P, d lnP/dt, d2 lnP/dt2")
    print(" * at t = ln y = NU_TAB_T0 + i NU_TAB_H. See the generator for F(y) and P(y). */")
    print("#define NU_TAB_T0 (%.17g)" % T0)
    print("#define NU_TAB_H %.17g" % H)
    print("#define NU_TAB_N %d" % N)
    print("static const double nu_tab[NU_TAB_N][6] = {")
    for i in range(N):
        r = row(T0 + i * H)
        print("    {" + ", ".join("%.17g" % v for v in r) + "},")
    print("};")


if __name__ == "__main__":
    main()
